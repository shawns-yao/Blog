-- +goose Down
-- Removes only derived RAG data and its configuration. Core content is preserved.
DROP TRIGGER trg_queue_rag_moment ON moment;
DROP FUNCTION queue_rag_moment();
DROP TABLE rag_chunk;
DROP TABLE rag_index_state;
DROP FUNCTION rag_source_hash(TEXT, TEXT, TEXT, TEXT, TEXT);
DELETE FROM sys_config WHERE config_key IN (
    'rag.chunkSize', 'rag.chunkOverlap', 'rag.minSimilarity', 'rag.indexVersion'
);
